#!/usr/bin/env bash
# Build the desktop application on Linux, then look at it.
#
# Runs inside the image `Dockerfile.check` builds. The source is read-only at
# /src and copied to /work, results go to /out. Phases are separate so a
# failing one can be re-run without paying for the ones before it:
#
#   check.sh            # everything
#   check.sh deps build # just those two
#
# The phases, in the order `check.sh` with no arguments runs them:
#
#   env            what this box is — WebKitGTK's version above all
#   deps           copy /src to /work, pnpm install
#   build          tauri build --bundles deb
#   install        apt install the deb, and read what it put where
#   render         Xvfb + openbox, four launches, screenshots, window probes
#   keychain       what the session bus says about org.freedesktop.secrets
#   probes         an instrumented build, run four ways, answering from
#                  inside the window
#   source_facts   what Linux actually compiles to, read out of the crates
#
# and these, which are not in the default run:
#
#   display        just the X server, for a session running several phases
#   theme          the same binary under a light and a dark GTK
#   mock           scripts/mock-server.mjs, so there is something to connect to
#   connect        drive the first-run flow with xdotool and photograph it
#   probe_runs     the four probe launches without rebuilding the binary
#   updater        generate a key, build a signed deb and a signed AppImage
#   appimage_run   launch the AppImage and photograph it
#
# **Do not edit this file while a run is in flight.** bash reads a script as
# it executes it, so an edit mid-run shifts the offsets under the interpreter
# and it starts executing something else. That happened twice here.
#
# Nothing here uses `set -e`. A probe that fails is a result — the point is to
# find out *how* each thing fails, so every step records its own verdict and
# the run continues.
set -uo pipefail

OUT=${OUT:-/out}
WORK=/work
APP=/work/desktop
DISPLAY_NUM=${DISPLAY_NUM:-99}
SCREEN=${SCREEN:-1440x900x24}
PROBE_PORT=${PROBE_PORT:-4499}
MOCK_PORT=${MOCK_PORT:-4401}
export DISPLAY=":${DISPLAY_NUM}"

mkdir -p "$OUT" "$OUT/logs"
LOG="$OUT/logs/check.log"

say()  { printf '\n\033[1m== %s\033[0m\n' "$*" | tee -a "$LOG"; }
note() { printf '   %s\n' "$*" | tee -a "$LOG"; }
fact() { printf '%s\n' "$*" >> "$OUT/facts.txt"; note "$*"; }

# ── the environment we are judging, written down ───────────────────────────────
phase_env() {
  say "environment"
  : > "$OUT/facts.txt"
  fact "uname: $(uname -srm)"
  fact "debian: $(cat /etc/debian_version 2>/dev/null)"
  fact "webkit2gtk-4.1: $(pkg-config --modversion webkit2gtk-4.1 2>&1)"
  fact "javascriptcoregtk-4.1: $(pkg-config --modversion javascriptcoregtk-4.1 2>&1)"
  fact "gtk+-3.0: $(pkg-config --modversion gtk+-3.0 2>&1)"
  fact "libsoup-3.0: $(pkg-config --modversion libsoup-3.0 2>&1)"
  fact "glib-2.0: $(pkg-config --modversion glib-2.0 2>&1)"
  fact "libwebkit2gtk-4.1-0 package: $(dpkg-query -W -f='${Version}' libwebkit2gtk-4.1-0 2>&1)"
  fact "rustc: $(rustc --version 2>&1)"
  fact "cargo: $(cargo --version 2>&1)"
  fact "node: $(node --version 2>&1)"
  fact "pnpm: $(pnpm --version 2>&1)"
  fact "openbox: $(openbox --version 2>&1 | head -1)"
  fact "secret service on the bus: $(ls /usr/share/dbus-1/services 2>/dev/null | tr '\n' ' ')"
  fact "gnome-keyring installed: $(dpkg-query -W -f='${Status}' gnome-keyring 2>&1)"
}

# ── the source, and the frontend's dependencies ───────────────────────────────
phase_deps() {
  say "copying the source and installing the frontend"
  mkdir -p "$APP"
  # Everything but the three things a Mac build leaves behind. A copied
  # `node_modules` would be a Mac's, and a copied `target/` would make the
  # first Linux build look warm.
  (cd /src && tar -cf - \
      --exclude=node_modules \
      --exclude=src-tauri/target \
      --exclude=dist \
      .) | (cd "$APP" && tar -xf -)
  note "desktop/ copied: $(du -sh "$APP" | cut -f1)"

  ( cd "$APP" && pnpm install --frozen-lockfile ) 2>&1 | tee "$OUT/logs/pnpm-install.log" | tail -5
  note "pnpm install: ${PIPESTATUS[0]:-?}"
}

# ── the build ─────────────────────────────────────────────────────────────────
#
# `--bundles deb` on the command line rather than in `tauri.conf.json`, whose
# committed targets are `app`, `dmg`, `nsis`, `msi` — macOS and Windows only.
# Nothing about the Linux build is in version control yet and this spike is not
# the change that puts it there.
phase_build() {
  say "building (tauri build --bundles deb)"
  local t0 t1
  t0=$(date +%s)
  ( cd "$APP" && pnpm tauri build --bundles deb ) 2>&1 | tee "$OUT/logs/tauri-build.log" | tail -40
  local code=${PIPESTATUS[0]}
  t1=$(date +%s)
  fact "tauri build --bundles deb: exit ${code}, $(( t1 - t0 ))s"

  # The first failure of this spike, and it is not a Linux failure — it is the
  # committed `createUpdaterArtifacts: true` next to a pubkey with no private
  # key in the environment. The bundle is already on disk when it happens, so
  # it is an exit code rather than a missing artifact. `unsigned.conf.json` is
  # in the tree for exactly this and makes it exit 0.
  if [ "$code" -ne 0 ]; then
    say "rebuilding with src-tauri/unsigned.conf.json"
    ( cd "$APP" && pnpm tauri build --bundles deb --config src-tauri/unsigned.conf.json ) \
      2>&1 | tee "$OUT/logs/tauri-build-unsigned.log" | tail -12
    fact "tauri build --bundles deb --config unsigned.conf.json: exit ${PIPESTATUS[0]}"
  fi
  find "$APP/src-tauri/target" -name '*.deb' -o -name '*.AppImage' -o -name '*.tar.gz' -o -name '*.sig' \
    2>/dev/null | sed 's|^|   artifact: |' | tee -a "$LOG"
  find "$APP/src-tauri/target" -name '*.deb' 2>/dev/null > "$OUT/debs.txt"
  fact "deb produced: $(wc -l < "$OUT/debs.txt") -> $(head -1 "$OUT/debs.txt")"
}

# Does the updater get artifacts on Linux? `createUpdaterArtifacts: true` is
# in the committed config, so if a `.deb` could self-update there would be a
# `.deb.tar.gz` and a `.sig` beside it. Timeboxed: AppImage bundling fetches
# tooling from the network and is allowed to fail.
phase_updater() {
  say "updater artifacts"
  local deb; deb=$(head -1 "$OUT/debs.txt")
  if [ -n "$deb" ]; then
    fact "beside the deb: $(ls "$(dirname "$deb")" | tr '\n' ' ')"
  fi

  # With a key, so the question stops being "was it signed" and becomes
  # "which bundles does the updater get artifacts for". The key is generated
  # here and thrown away; it does not match the pubkey in `tauri.conf.json`
  # and is not meant to.
  # `--ci --password ""`, because without them the CLI prompts on a tty that
  # is not there and aborts in `updater_signature.rs` with
  # `Os { code: 6, message: "No such device or address" }`.
  rm -f /tmp/ft-updater.key /tmp/ft-updater.key.pub
  ( cd "$APP" && pnpm tauri signer generate --ci --password "" -f -w /tmp/ft-updater.key ) \
    > "$OUT/logs/signer.log" 2>&1
  fact "signer generate: exit $?  key: $([ -f /tmp/ft-updater.key ] && echo yes || echo no)"
  export TAURI_SIGNING_PRIVATE_KEY="$(cat /tmp/ft-updater.key 2>/dev/null)"
  export TAURI_SIGNING_PRIVATE_KEY_PASSWORD=""

  ( cd "$APP" && pnpm tauri build --bundles deb ) > "$OUT/logs/tauri-deb-signed.log" 2>&1
  fact "signed deb build: exit $?"
  fact "deb dir after signing: $(ls "$APP/src-tauri/target/release/bundle/deb" 2>&1 | tr '\n' ' ')"

  ( cd "$APP" && timeout 1800 pnpm tauri build --bundles appimage ) \
    > "$OUT/logs/tauri-appimage.log" 2>&1
  fact "signed appimage build: exit $?"
  fact "appimage dir: $(ls -la "$APP/src-tauri/target/release/bundle/appimage" 2>&1 | tr '\n' '|')"
  fact "appimage log tail: $(tail -6 "$OUT/logs/tauri-appimage.log" | tr '\n' '|' | cut -c1-600)"
  unset TAURI_SIGNING_PRIVATE_KEY TAURI_SIGNING_PRIVATE_KEY_PASSWORD
}

# Does the AppImage actually run? It is the artifact the updater can install
# silently, so "it bundled" is not the same as "it works" — and an AppImage
# carries its own GTK and WebKitGTK, which is the part that can be wrong.
phase_appimage_run() {
  say "running the AppImage"
  local img; img=$(find "$APP/src-tauri/target/release/bundle/appimage" -name '*.AppImage' | head -1)
  if [ -z "$img" ]; then fact "appimage: nothing to run"; return 1; fi
  fact "appimage size: $(du -h "$img" | cut -f1)"
  pkill -f firetower-desktop 2>/dev/null; pkill -f AppImage 2>/dev/null; sleep 1
  chmod +x "$img"
  # No FUSE in a container, so it is extracted rather than mounted. The same
  # flag a user on a FUSE-less machine would need.
  ( env APPIMAGE_EXTRACT_AND_RUN=1 "$img" > "$OUT/logs/appimage-run.log" 2>&1 & )
  if wait_for_window 90; then fact "appimage: window up"; else fact "appimage: NO WINDOW"; fi
  sleep 10
  shoot_window "window-appimage"
  fact "appimage stderr: $(tail -4 "$OUT/logs/appimage-run.log" | tr '\n' '|' | cut -c1-400)"
  pkill -f AppImage 2>/dev/null
}

# ── install the deb, the way somebody would ───────────────────────────────────
phase_install() {
  say "installing the deb"
  local deb; deb=$(head -1 "$OUT/debs.txt")
  if [ -z "$deb" ]; then note "no deb to install"; return 1; fi
  apt-get update -qq >/dev/null 2>&1
  apt-get install -y --no-install-recommends "$deb" 2>&1 | tee "$OUT/logs/dpkg.log" | tail -10
  fact "installed: exit ${PIPESTATUS[0]}"
  fact "deb contents: $(dpkg-query -L firetower 2>/dev/null | tr '\n' ' ')"
  for f in /usr/share/applications/*iretower*; do
    [ -f "$f" ] && { fact ".desktop at $f"; cp "$f" "$OUT/"; sed 's|^|   |' "$f" | tee -a "$LOG"; }
  done
  # `firetower-desktop`, not `firetower`: the deb takes the binary's name from
  # the Cargo package and nothing in the committed config overrides it.
  fact "binary: $(command -v firetower-desktop || echo 'not on PATH')"
  fact "ldd not-found entries: $(ldd /usr/bin/firetower-desktop 2>/dev/null | grep -c 'not found')"
  fact "linked webkit: $(ldd /usr/bin/firetower-desktop 2>/dev/null | grep -oE 'libwebkit2gtk[^ ]*|libayatana[^ ]*|libdbus-1[^ ]*' | tr '\n' ' ')"
  fact "icons installed: $(dpkg-query -L firetower 2>/dev/null | grep -c '\.png')"
}

# ── a display, and something to manage the window ─────────────────────────────
#
# The window is `decorations: false`. With no window manager it is never
# mapped, raised or given focus — so a bare Xvfb would photograph an empty
# root and say nothing about the application. openbox is the smallest thing
# that makes the X server behave like a desktop.
start_display() {
  say "display"
  # The lock outlives the process. Without removing it a second run of this
  # script gets "server is already active for display 99", every launch then
  # panics in `gtk::rt::init`, and all of it looks like a Linux rendering
  # failure rather than a stale file.
  pkill -f "Xvfb :${DISPLAY_NUM}" 2>/dev/null; sleep 1
  rm -f "/tmp/.X${DISPLAY_NUM}-lock" "/tmp/.X11-unix/X${DISPLAY_NUM}"
  Xvfb ":${DISPLAY_NUM}" -screen 0 "$SCREEN" -ac -nolisten tcp > "$OUT/logs/xvfb.log" 2>&1 &
  for _ in $(seq 1 40); do xdpyinfo >/dev/null 2>&1 && break; sleep 0.25; done
  if ! xdpyinfo >/dev/null 2>&1; then
    fact "Xvfb: did not come up — $(tail -3 "$OUT/logs/xvfb.log" | tr '\n' '|')"
    return 1
  fi
  fact "Xvfb: $(xdpyinfo 2>&1 | grep -m1 'dimensions')"

  if [ -z "${DBUS_SESSION_BUS_ADDRESS:-}" ]; then
    eval "$(dbus-launch --sh-syntax)"
    export DBUS_SESSION_BUS_ADDRESS DBUS_SESSION_BUS_PID
  fi
  fact "session bus: ${DBUS_SESSION_BUS_ADDRESS:-none}"

  openbox > "$OUT/logs/openbox.log" 2>&1 &
  sleep 1.5
  fact "window manager: $(xprop -root _NET_SUPPORTING_WM_CHECK 2>&1 | head -1)"
  fact "wm name: $(xprop -root -notype _NET_WM_NAME 2>&1 | head -1)"
}

start_probe_collector() {
  pkill -f "probe.mjs" 2>/dev/null
  node /src/linux/probe.mjs "$PROBE_PORT" "$OUT" > "$OUT/logs/probe-collector.log" 2>&1 &
  sleep 0.5
}

# A screenshot, three ways, because on a bare X server one of them usually
# disagrees with you. The first that produces a non-empty file wins.
shoot() {
  local name=$1
  local png="$OUT/$name.png"
  rm -f "$png"
  if xwd -root -silent 2>/dev/null > "/tmp/$name.xwd" && [ -s "/tmp/$name.xwd" ]; then
    convert "/tmp/$name.xwd" "$png" 2>/dev/null
  fi
  [ -s "$png" ] || import -window root "$png" 2>/dev/null
  [ -s "$png" ] || scrot -o "$png" 2>/dev/null
  if [ -s "$png" ]; then
    # Mean and standard deviation across the whole frame. A blank window is
    # not "black" — it is *uniform*, and the deviation is what says so.
    local stats
    stats=$(identify -format '%wx%h mean=%[fx:mean*255] sd=%[fx:standard_deviation*255] colors=%k' "$png" 2>/dev/null)
    fact "shot $name.png: $stats"
  else
    fact "shot $name.png: nothing could photograph the root window"
  fi
}

# The application's own window, cropped out of the root, so a blank *window*
# is distinguishable from a blank desktop.
shoot_window() {
  local name=$1
  local id; id=$(xdotool search --name '^Firetower$' 2>/dev/null | head -1)
  [ -z "$id" ] && id=$(xdotool search --class -- firetower 2>/dev/null | head -1)
  if [ -z "$id" ]; then fact "window $name: no window named Firetower"; return 1; fi
  local geom; geom=$(xdotool getwindowgeometry --shell "$id")
  eval "$geom"
  fact "window $name: id=$id ${WIDTH}x${HEIGHT} at +${X}+${Y}"
  if xwd -id "$id" -silent 2>/dev/null > "/tmp/w-$name.xwd" && [ -s "/tmp/w-$name.xwd" ]; then
    convert "/tmp/w-$name.xwd" "$OUT/$name.png" 2>/dev/null
  fi
  [ -s "$OUT/$name.png" ] || import -window "$id" "$OUT/$name.png" 2>/dev/null
  if [ -s "$OUT/$name.png" ]; then
    fact "window shot $name.png: $(identify -format '%wx%h mean=%[fx:mean*255] sd=%[fx:standard_deviation*255] colors=%k' "$OUT/$name.png")"
  else
    fact "window shot $name.png: could not photograph the window itself"
  fi
}

wait_for_window() {
  for _ in $(seq 1 "${1:-60}"); do
    xdotool search --name '^Firetower$' 2>/dev/null | grep -q . && return 0
    sleep 0.5
  done
  return 1
}

# ── launch the installed application and photograph it ────────────────────────
#
# Twice: once as the `.desktop` file would start it, and once with
# `WEBKIT_DISABLE_DMABUF_RENDERER=1`. That variable is the known workaround for
# WebKitGTK 2.4x rendering nothing through the DMA-BUF path on some drivers and
# in VMs, and whether it is *needed here* is the headline question.
launch() {
  local tag=$1; shift
  say "launching: $tag"
  local bin=/usr/bin/firetower-desktop
  pkill -f "$bin" 2>/dev/null; sleep 1
  rm -rf /root/.local/share/cloud.firetower.desktop 2>/dev/null
  ( env "$@" "$bin" > "$OUT/logs/app-$tag.log" 2>&1 & echo $! > /tmp/app.pid )
  if wait_for_window 60; then
    fact "$tag: window appeared after $(cat /tmp/app.pid) started"
  else
    fact "$tag: NO WINDOW after 30s"
    fact "$tag: stderr: $(tail -5 "$OUT/logs/app-$tag.log" | tr '\n' '|')"
    return 1
  fi
  # Give React, the webfonts and the first paint time to happen.
  sleep 8
  shoot "root-$tag"
  shoot_window "window-$tag"
  fact "$tag: app log: $(wc -l < "$OUT/logs/app-$tag.log") lines, $(grep -ci 'error\|warn\|critical' "$OUT/logs/app-$tag.log") error/warn lines"
}

# ── the frameless window: can it be moved, and can it be resized? ─────────────
#
# Resize is the one most likely to be missing. `decorations: false` turns off
# GTK's own frame, and openbox will not add one to a window that asked for
# none — so there may be no edge to grab even though the window is marked
# resizable. Both are tested: what the window *says* (its hints), what a
# pointer drag at the corner actually does, and what a programmatic resize
# does. Those three can disagree, and the difference is the finding.
phase_window_behaviour() {
  say "frameless window: hints, drag, resize"
  local id; id=$(xdotool search --name '^Firetower$' | head -1)
  if [ -z "$id" ]; then fact "window behaviour: no window"; return 1; fi

  fact "_MOTIF_WM_HINTS: $(xprop -id "$id" _MOTIF_WM_HINTS 2>&1 | head -1)"
  fact "_GTK_FRAME_EXTENTS: $(xprop -id "$id" _GTK_FRAME_EXTENTS 2>&1 | head -1)"
  fact "_NET_WM_ALLOWED_ACTIONS: $(xprop -id "$id" _NET_WM_ALLOWED_ACTIONS 2>&1 | tr '\n' ' ')"
  fact "WM_NORMAL_HINTS: $(xprop -id "$id" WM_NORMAL_HINTS 2>&1 | tr '\n' ' ' | cut -c1-400)"
  fact "WM_CLASS: $(xprop -id "$id" WM_CLASS 2>&1 | head -1)"
  fact "_NET_WM_STATE: $(xprop -id "$id" _NET_WM_STATE 2>&1 | head -1)"
  fact "frame vs client: $(xwininfo -id "$id" | grep -E 'Absolute|Width|Height|Border' | tr '\n' ' ')"
  fact "openbox decorated: $(xwininfo -id "$(xdotool getwindowfocus 2>/dev/null || echo "$id")" -tree 2>/dev/null | head -3 | tr '\n' ' ')"

  local before after
  # 1. drag the title bar. y=18 is inside `--chrome-title`; x=520 is between
  #    the org/user button and the window controls, so it is bar and not a
  #    control. This is `startDragging()` -> `gtk_window_begin_move_drag`.
  before=$(xdotool getwindowgeometry --shell "$id" | tr '\n' ' ')
  eval "$(xdotool getwindowgeometry --shell "$id")"
  xdotool mousemove $((X + 520)) $((Y + 18)) mousedown 1 2>/dev/null
  sleep 0.4
  xdotool mousemove_relative -- 140 90 2>/dev/null; sleep 0.4
  xdotool mousemove_relative -- 20 10 2>/dev/null; sleep 0.4
  xdotool mouseup 1 2>/dev/null; sleep 1.2
  after=$(xdotool getwindowgeometry --shell "$id" | tr '\n' ' ')
  fact "drag by the title bar: before [$before] after [$after]"
  shoot_window "window-after-drag"

  # 2. drag the bottom-right corner, which is where a resize grip would be.
  eval "$(xdotool getwindowgeometry --shell "$id")"
  before="${WIDTH}x${HEIGHT}"
  xdotool mousemove $((X + WIDTH - 1)) $((Y + HEIGHT - 1)) mousedown 1 2>/dev/null
  sleep 0.4
  xdotool mousemove_relative -- -200 -120 2>/dev/null; sleep 0.5
  xdotool mouseup 1 2>/dev/null; sleep 1.2
  eval "$(xdotool getwindowgeometry --shell "$id")"
  fact "drag the bottom-right corner: ${before} -> ${WIDTH}x${HEIGHT}"

  # 3. the window manager's own resize, with no pointer involved. If this
  #    works and (2) did not, the window is resizable and there is simply
  #    nothing to grab — which is a different problem with a different fix.
  xdotool windowsize "$id" 1000 700 2>/dev/null; sleep 1.5
  eval "$(xdotool getwindowgeometry --shell "$id")"
  fact "xdotool windowsize 1000x700 -> ${WIDTH}x${HEIGHT}"
  shoot_window "window-resized"

  # 4. and below the configured minimum, which the window should refuse.
  xdotool windowsize "$id" 400 300 2>/dev/null; sleep 1.5
  eval "$(xdotool getwindowgeometry --shell "$id")"
  fact "xdotool windowsize 400x300 (minWidth 880, minHeight 560) -> ${WIDTH}x${HEIGHT}"

  xdotool windowsize "$id" 1280 820 2>/dev/null; sleep 1
}

# ── the probe build ───────────────────────────────────────────────────────────
#
# The same frontend bundle with `probe.js` appended to `dist/index.html`, so
# the answers come from inside the real window: the real WebKitGTK, the real
# CSP, the real bridge. `beforeBuildCommand` is emptied through `--config` so
# `pnpm build` does not overwrite the patched dist — a build-time override on
# the harness's side, not a change to the committed config.
phase_probe_build() {
  say "probe build"
  ( cd "$APP" && pnpm build ) > "$OUT/logs/vite-build.log" 2>&1
  fact "vite build: exit $?"
  fact "dist: $(ls "$APP/dist" | tr '\n' ' ')"
  fact "emitted css: $(find "$APP/dist" -name '*.css' | head -1)"
  local css; css=$(find "$APP/dist" -name '*.css' | head -1)
  if [ -n "$css" ]; then
    fact "css bytes: $(wc -c < "$css")"
    fact "css @property blocks: $(grep -o '@property' "$css" | wc -l)"
    fact "css oklch(): $(grep -o 'oklch(' "$css" | wc -l)"
    fact "css color-mix(): $(grep -o 'color-mix(' "$css" | wc -l)"
    fact "css woff2 refs: $(grep -o '\.woff2' "$css" | wc -l)"
    cp "$css" "$OUT/app.css"
  fi

  # The probe build, and only the probe build, runs with the CSP off. The
  # committed policy is `default-src 'self'` with no `script-src`, and under
  # it an added script is refused — silently, with the same symptom as a probe
  # that ran and found nothing. The application's own CSP is already proven by
  # the installed `.deb`: it loads its bundle and reaches the control plane.
  cat > "$APP/src-tauri/probe.conf.json" <<JSON
{ "\$schema": "https://schema.tauri.app/config/2",
  "build": { "beforeBuildCommand": "" },
  "app": { "security": { "csp": null } },
  "bundle": { "active": false, "createUpdaterArtifacts": false } }
JSON
  # A file, not an inline block. The application's committed CSP is
  # `default-src 'self'` with no `script-src`, so an inline `<script>` is
  # refused and the probe runs not at all — which looks exactly like a probe
  # that found nothing. Served from the bundle, it is `'self'` and allowed.
  {
    echo "window.__FT_PROBE_PORT__=${PROBE_PORT};window.__FT_PROBE_PHASE__='${1:-probe}';"
    cat /src/linux/probe.js
  } > "$APP/dist/probe.js"
  # Inside `</body>`, not appended after `</html>`. Tauri parses and
  # re-serialises `index.html` when it injects the CSP meta tag, and anything
  # sitting outside the document is not guaranteed to survive that trip — a
  # script that is silently dropped at build time looks exactly like a script
  # that ran and found nothing.
  sed -i "s|</body>|  <script src=\"/probe.js\"></script>\n  </body>|" "$APP/dist/index.html"
  grep -q 'probe.js' "$APP/dist/index.html" || echo "<script src=\"/probe.js\"></script>" >> "$APP/dist/index.html"
  note "dist/probe.js: $(wc -c < "$APP/dist/probe.js") bytes; index.html $(wc -c < "$APP/dist/index.html") bytes"

  # The frontend is embedded by `generate_context!` in main.rs, so the crate
  # has to be re-expanded for a changed dist to reach the binary.
  touch "$APP/src-tauri/src/main.rs"
  ( cd "$APP" && pnpm tauri build --no-bundle --config src-tauri/probe.conf.json ) \
    > "$OUT/logs/probe-build.log" 2>&1
  fact "probe build: exit $?  -> $(ls -la "$APP/src-tauri/target/release/firetower-desktop" 2>&1 | tail -1)"
}

# Run the probe binary once per environment and keep whatever it posted.
#
# Three files arrive per run — the liveness ping, the page, and the bridge —
# under the label the binary was built with. They are renamed to the tag here
# so one build can be run under several environments.
launch_probe() {
  local tag=$1; shift
  say "probe run: $tag"
  local bin="$APP/src-tauri/target/release/firetower-desktop"
  pkill -f firetower-desktop 2>/dev/null; pkill -f '/usr/bin/firetower-desktop' 2>/dev/null; sleep 1
  # Only the build-label files. `probe-*.json` would take the previous
  # variant's renamed results with it, which is a harness bug that looks
  # exactly like a run that posted nothing.
  rm -f "$OUT"/probe-p.json "$OUT"/probe-p-alive.json "$OUT"/probe-p-bridge.json
  ( env "$@" "$bin" > "$OUT/logs/probe-app-$tag.log" 2>&1 & )
  if wait_for_window 60; then fact "probe $tag: window up"; else fact "probe $tag: NO WINDOW"; fi
  sleep 3
  fact "probe $tag: titles now [$(xdotool search --class -- firetower-desktop 2>/dev/null | while read -r w; do printf '%s;' "$(xdotool getwindowname "$w" 2>/dev/null)"; done)]"
  # Long, because the bridge half of the probe waits on D-Bus names that do
  # not exist here and each one can sit for its timeout.
  sleep 40
  shoot_window "window-probe-$tag"
  local kept=0
  for f in "$OUT"/probe-p.json "$OUT"/probe-p-alive.json "$OUT"/probe-p-bridge.json; do
    [ -f "$f" ] || continue
    local base; base=$(basename "$f")
    # probe-<buildlabel>[-alive|-bridge].json -> probe-<tag>[-alive|-bridge].json
    local suffix=""
    case "$base" in
      *-alive.json) suffix="-alive" ;;
      *-bridge.json) suffix="-bridge" ;;
    esac
    mv "$f" "$OUT/probe-${tag}${suffix}.json"
    kept=$((kept + 1))
  done
  fact "probe $tag: $kept report(s) kept"
  fact "probe $tag app stderr: $(grep -iE 'error|critical|warn|fail' "$OUT/logs/probe-app-$tag.log" | head -3 | tr '\n' '|')"
}

# ── the keychain, from the outside too ────────────────────────────────────────
#
# The probe asks the real application. This asks the bus directly, so the
# error string can be attributed to the absence of a Secret Service rather
# than to anything Firetower did.
phase_keychain() {
  say "secret service"
  fact "org.freedesktop.secrets activatable: $(ls /usr/share/dbus-1/services/ 2>/dev/null | grep -ci secret)"
  fact "dbus-send to the secrets service: $(timeout 20 dbus-send --session --print-reply --dest=org.freedesktop.secrets /org/freedesktop/secrets org.freedesktop.DBus.Properties.GetAll string:org.freedesktop.Secret.Service 2>&1 | head -3 | tr '\n' '|')"
  fact "names on the session bus: $(timeout 20 dbus-send --session --print-reply --dest=org.freedesktop.DBus /org/freedesktop/DBus org.freedesktop.DBus.ListNames 2>&1 | grep -o '"[a-z0-9._-]*"' | tr '\n' ' ' | cut -c1-500)"
}

# ── what the tree actually compiles to on Linux ──────────────────────────────
#
# Read out of the crates the build resolved, not out of documentation: whether
# `set_badge_count` does anything on this platform, and whether the capture
# stub is the branch Linux takes.
phase_source_facts() {
  say "what Linux compiles to"
  local reg=/usr/local/cargo/registry/src
  fact "tao: $(ls "$reg"/*/ 2>/dev/null | grep -o 'tao-[0-9.]*' | head -1)"
  fact "tauri: $(ls "$reg"/*/ 2>/dev/null | grep -oE '^tauri-[0-9][0-9.]*' | head -1)"
  fact "wry: $(ls "$reg"/*/ 2>/dev/null | grep -o 'wry-[0-9.]*' | head -1)"
  for f in $(find "$reg" -path '*/tao-*/src/platform_impl/linux/window.rs' 2>/dev/null | head -1); do
    fact "tao linux set_badge_count: $(grep -n -A 4 'fn set_badge_count' "$f" | tr '\n' '|' | cut -c1-400)"
    fact "tao linux set_progress_bar: $(grep -c 'fn set_progress_bar' "$f")"
  done
  for f in $(find "$reg" -path '*/tauri-2*/src/window/mod.rs' -o -path '*/tauri-2*/src/webview/window.rs' 2>/dev/null | head -2); do
    fact "tauri set_badge_count in $(basename "$f"): $(grep -n 'fn set_badge_count' "$f" | head -1)"
  done
  for f in $(find "$reg" -path '*/tauri-plugin-updater-*/src/updater.rs' 2>/dev/null | head -1); do
    fact "updater linux branches: $(grep -n 'target_os = \"linux\"' "$f" | wc -l)"
    fact "updater AppImage mentions: $(grep -ci appimage "$f")"
    fact "updater linux error text: $(grep -n -i 'appimage' "$f" | head -6 | tr '\n' '|' | cut -c1-600)"
  done
  for f in $(find "$reg" -path '*/webkit2gtk-2*/src/auto/web_view.rs' 2>/dev/null | head -1); do
    # The binding names it `snapshot`; `webkit_web_view_get_snapshot` is the
    # C symbol it carries as a doc alias.
    fact "webkit2gtk binding snapshot(): $(grep -c 'webkit_web_view_get_snapshot' "$f")"
    fact "snapshot signature: $(grep -n -A 6 'fn snapshot<' "$f" | tr '\n' '|' | cut -c1-420)"
  done
  cargo tree --manifest-path "$APP/src-tauri/Cargo.toml" --target aarch64-unknown-linux-gnu -e normal \
    > "$OUT/logs/cargo-tree-linux.txt" 2>&1
  fact "linux dep tree: $(wc -l < "$OUT/logs/cargo-tree-linux.txt") lines -> logs/cargo-tree-linux.txt"
  grep -E '^[├└│ ]*(webkit2gtk|gtk|soup3|dbus|libappindicator|keyring|tao|wry) ' "$OUT/logs/cargo-tree-linux.txt" \
    | head -20 | sed 's|^|   |' | tee -a "$LOG"
}

