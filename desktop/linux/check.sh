# ── which theme does a Linux desktop get? ────────────────────────────────────
#
# `tauri.conf.json` asks for `"theme": "Dark"`, and `src/theme.ts` follows the
# machine through `prefers-color-scheme` unless somebody has chosen. WebKitGTK
# answers that query out of GtkSettings, so what the window was configured
# with and what the page believes can disagree — and on Linux they do. Both
# GTK variants are launched so the screenshots say which.
phase_theme() {
  launch "gtk-dark" GTK_THEME=Adwaita:dark
  launch "gtk-light" GTK_THEME=Adwaita
}

# ── a control plane to connect to ────────────────────────────────────────────
#
# `scripts/mock-server.mjs` is already in the tree for driving the client
# without a Postgres, and it answers `/api/v1/bootstrap` and `/auth/login`, so
# the whole first-run flow can be walked. Worth it: the connect screen proves
# the webview paints, and the dashboard behind it proves the *application*
# does — six hundred elements of grid, chart, avatar and monospace.
phase_mock() {
  say "mock control plane"
  pkill -f mock-server.mjs 2>/dev/null; sleep 0.5
  ( cd "$APP" && node scripts/mock-server.mjs "$MOCK_PORT" ) > "$OUT/logs/mock.log" 2>&1 &
  for _ in $(seq 1 20); do
    curl -fsS "http://localhost:${MOCK_PORT}/api/v1/bootstrap" >/dev/null 2>&1 && break
    sleep 0.5
  done
  fact "mock /bootstrap: $(curl -fsS "http://localhost:${MOCK_PORT}/api/v1/bootstrap" 2>&1 | cut -c1-200)"
}

# Walk the first-run flow with the keyboard, photographing each screen.
phase_connect() {
  say "connecting to the mock control plane"
  launch "connect"
  local id; id=$(xdotool search --name '^Firetower$' | head -1)
  if [ -z "$id" ]; then fact "connect: no window"; return 1; fi
  xdotool windowactivate --sync "$id" 2>/dev/null; sleep 1

  # The address field is `autoFocus`, so there is nothing to click first.
  xdotool type --delay 45 "http://localhost:${MOCK_PORT}"
  sleep 1
  shoot_window "connect-1-address"
  xdotool key --clearmodifiers Return
  sleep 5
  shoot_window "connect-2-found"

  # Username is `autoFocus` on the next screen; Tab reaches the password.
  xdotool type --delay 45 "kevin"
  xdotool key --clearmodifiers Tab
  xdotool type --delay 45 "hunter2"
  sleep 0.8
  shoot_window "connect-3-credentials"
  xdotool key --clearmodifiers Return
  sleep 10
  shoot_window "connect-4-signed-in"
  fact "connect: title now $(xdotool getwindowname "$id" 2>/dev/null)"

  # The whole point of the big screen: a dashboard is a thousand elements of
  # grid, ring, avatar, chart and monospace, and that is what a broken
  # stylesheet shows up in.
  # Named by the shortcut rather than by a guess at what sits behind it —
  # the rail's destinations are the app's to decide, not this script's.
  xdotool key --clearmodifiers ctrl+2; sleep 4; shoot_window "app-rail-2"
  xdotool key --clearmodifiers ctrl+1; sleep 4; shoot_window "app-rail-1"
  xdotool key --clearmodifiers ctrl+4; sleep 4; shoot_window "app-rail-4"
  xdotool key --clearmodifiers ctrl+5; sleep 4; shoot_window "app-rail-5"

  # And in dark, which is what the design is drawn for.
  pkill -f '/usr/bin/firetower-desktop' 2>/dev/null; sleep 2
  ( env GTK_THEME=Adwaita:dark /usr/bin/firetower-desktop > "$OUT/logs/app-connected-dark.log" 2>&1 & )
  wait_for_window 60 && sleep 12
  shoot_window "app-dark-after-restart"
  fact "after restart with no Secret Service: see app-dark-after-restart.png"
}

